package in.guvi.fraud.db;
import java.sql.*;
public final class Database {
 private static final String URL="jdbc:h2:file:"+System.getProperty("user.home")+"/frauddb2;AUTO_SERVER=TRUE";
 private Database(){}
 public static Connection getConnection() throws SQLException{return DriverManager.getConnection(URL,"sa","");}
 public static void initialize(){
  try{Class.forName("org.h2.Driver");try(Connection c=getConnection();Statement s=c.createStatement()){
   s.execute("CREATE TABLE IF NOT EXISTS transactions(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id VARCHAR(80), amount DECIMAL(14,2), payment_method VARCHAR(50), location VARCHAR(100), created_at TIMESTAMP, risk_score INT, decision VARCHAR(20), explanation VARCHAR(1000), reviewed BOOLEAN DEFAULT FALSE, review_note VARCHAR(500) DEFAULT '')");
   s.execute("CREATE TABLE IF NOT EXISTS settings(setting_key VARCHAR(80) PRIMARY KEY, setting_value VARCHAR(100))");
   s.execute("MERGE INTO settings KEY(setting_key) VALUES('check','30')");
   s.execute("MERGE INTO settings KEY(setting_key) VALUES('review','60')");
  }}catch(Exception e){throw new IllegalStateException("Database initialization failed",e);}
 }
}
